import contextlib
import io
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import check_docs  # noqa: E402

VALID = "---\ntitle: A\nsummary: s\nread-when: now\nstatus: active\ncovers: []\n---\nbody\n"


def run(root, *extra):
    out, err = io.StringIO(), io.StringIO()
    with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
        code = check_docs.main(["--root", str(root), *extra])
    return code, out.getvalue(), err.getvalue()


def write(root, relative, text):
    path = Path(root) / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return path


def git(root, *args):
    subprocess.run(
        ["git", "-c", "user.name=t", "-c", "user.email=t@t", *args],
        cwd=root, check=True, capture_output=True,
    )


class CheckDocsTest(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.root = Path(self.temp.name)
        self.addCleanup(self.temp.cleanup)

    def test_valid_doc_passes(self):
        write(self.root, "context/a.md", VALID)
        self.assertEqual(run(self.root)[0], 0)

    def test_missing_field_fails(self):
        write(self.root, "context/a.md", "---\ntitle: A\n---\n")
        code, out, err = run(self.root)
        self.assertEqual(code, 1)
        self.assertIn("a.md: missing field summary", out + err)

    def test_unknown_field_fails(self):
        write(self.root, "context/a.md", VALID.replace("---\nbody", "extra: 1\n---\nbody"))
        code, out, err = run(self.root)
        self.assertEqual(code, 1)
        self.assertIn("unknown field extra", out + err)

    def test_profile_frontmatter_override(self):
        write(self.root, "AGENTS.md", "## Repo profile\n- Frontmatter: title, owner\n")
        write(self.root, "context/a.md", "---\ntitle: A\nowner:\n---\n")
        self.assertEqual(run(self.root)[0], 0)
        write(self.root, "context/b.md", VALID)
        self.assertEqual(run(self.root)[0], 1)

    def test_unindexed_warns_but_passes(self):
        write(self.root, "context/a.md", "# plain\n")
        code, out, err = run(self.root)
        self.assertEqual(code, 0)
        self.assertIn("a.md: unindexed (no frontmatter)", out + err)

    def test_malformed_frontmatter_fails(self):
        write(self.root, "context/a.md", "---\ntitle: x\n- item\n---\n")
        self.assertEqual(run(self.root)[0], 1)

    def test_generated_readme_skipped(self):
        write(self.root, "context/README.md", "<!-- Generated by tools/build_index.py; do not edit by hand. -->\n# x\n")
        self.assertEqual(run(self.root)[0], 0)

    def test_broken_link_fails_and_good_links_pass(self):
        write(self.root, "context/b.md", VALID)
        write(self.root, "context/a.md", VALID + "[ok](b.md#top) [web](https://x.y) [anchor](#top)\n")
        self.assertEqual(run(self.root)[0], 0)
        write(self.root, "context/c.md", VALID + "[bad](missing.md)\n")
        code, out, err = run(self.root)
        self.assertEqual(code, 1)
        self.assertIn("c.md: broken link target missing.md", out + err)

    def test_drift_warning_with_base(self):
        git(self.root, "init")
        doc = VALID.replace("covers: []", "covers: [src/*.py]")
        write(self.root, "context/a.md", doc)
        write(self.root, "src/x.py", "1\n")
        git(self.root, "add", "-A")
        git(self.root, "commit", "-m", "base")
        write(self.root, "src/x.py", "2\n")
        git(self.root, "commit", "-am", "code")
        code, out, err = run(self.root, "--base", "HEAD~1")
        self.assertEqual(code, 0)
        self.assertIn("covers changed files but was not updated: src/x.py", out + err)
        write(self.root, "context/a.md", doc + "more\n")
        git(self.root, "commit", "-am", "doc")
        code, out, err = run(self.root, "--base", "HEAD~2")
        self.assertEqual(code, 0)
        self.assertNotIn("not updated", out + err)

    def test_bad_ref_is_usage_error(self):
        git(self.root, "init")
        write(self.root, "context/a.md", VALID)
        git(self.root, "add", "-A")
        git(self.root, "commit", "-m", "base")
        self.assertEqual(run(self.root, "--base", "nope")[0], 2)

    def test_not_a_git_repo_is_usage_error(self):
        write(self.root, "context/a.md", VALID)
        self.assertEqual(run(self.root, "--base", "HEAD")[0], 2)


if __name__ == "__main__":
    unittest.main()
