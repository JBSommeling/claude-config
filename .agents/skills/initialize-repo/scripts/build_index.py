#!/usr/bin/env python3
"""Generate README.md indexes for every folder of documents under context/."""

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import frontmatter  # noqa: E402

BANNER = "<!-- Generated by tools/build_index.py; do not edit by hand. -->"
INDEX_NAME = "README.md"


def format_text(value):
    if isinstance(value, list):
        return ", ".join(value)
    return value or ""


def escape_link_text(text):
    return text.replace("]", "\\]")


def describe_document(path):
    """Return the bullet for a document, or None when it cannot be indexed."""
    try:
        fields = frontmatter.parse_frontmatter(path.read_text(encoding="utf-8"))
    except (frontmatter.FrontmatterError, UnicodeDecodeError):
        return None
    if fields is None:
        return None
    return format_bullet(fields, path.name)


def format_bullet(fields, name):
    link_text = escape_link_text(format_text(fields.get("title")) or name)
    line = f"- [{link_text}](<{name}>)"
    if format_text(fields.get("summary")):
        line += f" — {format_text(fields['summary'])}"
    if format_text(fields.get("read-when")):
        line += f" · read when: {format_text(fields['read-when'])}"
    if format_text(fields.get("status")):
        line += f" · status: {format_text(fields['status'])}"
    return line


def render_index(folder, indexed_lines, unindexed_names, subfolder_names):
    lines = [BANNER, "", f"# {folder.name.capitalize()} index", ""]
    lines += indexed_lines
    if subfolder_names:
        lines += ["", "## Folders", ""]
        lines += [f"- [{escape_link_text(name)}](<{name}/{INDEX_NAME}>)" for name in subfolder_names]
    if unindexed_names:
        lines += ["", "## Unindexed", ""]
        lines += [f"- [{escape_link_text(name)}](<{name}>)" for name in unindexed_names]
    return "\n".join(lines) + "\n"


def collect_indexes(folder, indexes, is_root=False):
    """Fill indexes with {README path: text}; return True when folder gets one."""
    indexed_lines, unindexed_names = [], []
    documents = sorted(
        path for path in folder.iterdir()
        if not path.is_symlink() and path.is_file() and path.suffix == ".md" and path.name != INDEX_NAME
    )
    for path in documents:
        line = describe_document(path)
        if line is None:
            unindexed_names.append(path.name)
        else:
            indexed_lines.append(line)
    subfolder_names = [
        child.name for child in sorted(folder.iterdir())
        if not child.is_symlink() and child.is_dir() and collect_indexes(child, indexes)
    ]
    if not (documents or subfolder_names or is_root):
        return False
    indexes[folder / INDEX_NAME] = render_index(
        folder, indexed_lines, unindexed_names, subfolder_names
    )
    return True


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", default=".", help="target repo root (default: cwd)")
    parser.add_argument("--check", action="store_true", help="report stale indexes without writing")
    arguments = parser.parse_args(argv)

    context_dir = Path(arguments.root) / "context"
    if not context_dir.is_dir():
        print("no context/ directory; nothing to do")
        return 0
    indexes = {}
    collect_indexes(context_dir, indexes, is_root=True)

    stale, blocked = [], []
    for path, text in sorted(indexes.items()):
        if path.is_symlink():
            blocked.append(path)
            continue
        if not path.resolve().is_relative_to(context_dir.resolve()):
            blocked.append(path)
            continue
        try:
            current = path.read_text(encoding="utf-8") if path.is_file() else None
        except UnicodeDecodeError:
            blocked.append(path)
            continue
        if current == text:
            continue
        first_line = current.splitlines()[0].strip() if current else ""
        if current is not None and first_line != BANNER:
            blocked.append(path)
            continue
        stale.append(path)
        if not arguments.check:
            path.write_text(text, encoding="utf-8")
    for path in blocked:
        print(f"hand-written index blocks generation: {path} (rename it, e.g. to overview.md, then re-run)")
    if arguments.check:
        for path in stale:
            print(f"stale or missing index: {path}")
        return 1 if stale or blocked else 0
    for path in stale:
        print(f"wrote {path}")
    return 1 if blocked else 0


if __name__ == "__main__":
    sys.exit(main())
